SYSTEM_PROMPT = """Your task is to create a short insightful animation educational video on physics and chemistry concept and upload it to an AWS S3 bucket.
You are granted access to coding skills that will greatly aid you in writing and executing Python code in order to generate such video.
ONLY use ManimGL library and commands to accomplish the video.

## `manim-composer`
Transforms vague video ideas into detailed scene-by-scene plans (`scenes.md`). 
Conducts research, self-clarify the audience/scope/focus and outputs comprehensive scene specifications ready for implementation with ManimGL.
Use this skill BEFORE writing any Manim code.

## `manimgl-best-practices`
OpenGL-based animation engine with interactive development. Use this skill to create excutable Python code and run CLI commans based on the scene specifications generated by `manim-composer` skill.

You are also equipped a tool to upload the video an AWS S3 bucket.

## `upload_video_to_s3_bucket`
Use this tool to upload the completed video to the eduvid-storage S3 bucket

CRITICAL: Call the 'code-reviewer' subagent using the task tool to review and fix any overlapping components issues before executing the code.
"""


model = ChatBedrockConverse(
    model=all_secrets["model"], 
    client=get_client(),
    region_name=all_secrets["region"]
)


def agent_node(state: WorkflowState):
    question = state["question"]
    answer = state["answer"]

    sandbox = Sandbox.create(template="eduvid-sandbox", api_key=e2b_api_key, timeout=3600, secure=True)
    sandbox_backend = ScopedE2BSandbox(sandbox=sandbox)

    @tool("upload_video", 
      description="Upload a generated MP4 video file to the eduvid-storage S3 bucket. Use this function to upload any successfully generated video")
    def upload_video_to_s3_bucket(local_video_path: Path) -> str:

        """Upload the generated MP4 video file to the S3 bucket.
        
        Args:
            local_video_path: Path to the local MP4 file.
        
        Returns:
            S3 presigned URL
        
        Raises:
            Error if the upload fails.
        """

        s3_key = f"videos/{uuid.uuid4()}.mp4"
        
        try:
            s3_client = boto3.client("s3")
        
            # Generate a presigned URL
            s3_url = s3_client.generate_presigned_url(
                ClientMethod="get_object",
                Params={"Bucket": "eduvid-storage", "Key": s3_key},
                ExpiresIn=7 * 24 * 60 * 60,
            )

            logger.info("UPLOADING VIDEO...")
            try:
                content = sandbox.files.read(local_video_path, format="bytes")
                s3_client.put_object(
                    Bucket="eduvid-storage",
                    Key=s3_key,
                    Body=content,
                    ContentType='video/mp4'
                )
                logger.info("UPLOADLING FINISHED!")
            except Exception as err:
                logger.error(f"ERROR IN UPLOADING VIDEO: {str(err)}")
                raise err    
            
            return s3_url
        
        except Exception as err:
            logger.error(f"Failed to upload video to S3: {err}")
            raise RuntimeError(
                f"Failed to upload video to S3: {err}"
            ) from err

    code_reviewer_subagent["middleware"].append(
        FilesystemMiddleware(
            tools=["read_file", "ls", "grep", "edit_file"],
            backend=sandbox_backend
        )
    )

    agent = create_deep_agent(
        name="eduvid-manim-agent",
        model=model,
        skills=["/home/user/manim/"], 
        tools=[upload_video_to_s3_bucket],
        backend=sandbox_backend,
        subagents=[code_reviewer_subagent],
        system_prompt=SYSTEM_PROMPT
    )

    
    state["iterations"] = state.get("iterations", 0) + 1
    logger.info(f"Iteration no. {state["iterations"]}")
    error = state.get("agent_error", "")

    user_promt = ""

    if len(error):
        user_prompt = """The previous iteration causes an error below:
{error}

in an attempt to create an animation video for this scientifc concept:
Question:
{question}

Answer:
{answer}

Inspect the possible root causes of this error, whether it lies in the code generation or bash commands, and direct the resolution.
""" 

        user_prompt = user_prompt.format(error=error, question=question, answer=answer)     
    else:  
        user_prompt = """Create a single insightful animation video to visualize this scientific concept which contains a question-answer pair below.
Question:
{question}

Answer:
{answer}    
"""
        user_prompt = user_prompt.format(question=question, answer=answer)
    result, presigned_url = "", ""
    try:
        result = agent.invoke({"messages": [{"role": "user", "content": user_prompt}]})
        for message in result["messages"]:
            if isinstance(message, ToolMessage):
                if message.name == "upload_video":
                    presigned_url = message.content
                    break
        logger.info(f"S3 PRESIGNED URL: {presigned_url}")
        state["video_url"] = presigned_url  # temporary
    except Exception as err:
        state["agent_error"] = str(err)
        logger.error(f"ERROR IN AGENT NODE: {str(err)}")

    try:
        sandbox.kill()
    except Exception as err:
        state["agent_error"] = str(err)
        logger.error(f"ERROR WHILE TERMINATING SANDBOX: {str(err)}")
        
    return state
